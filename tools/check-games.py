#!/usr/bin/env python3
"""Weekly broken-game check for UBG45.

  python3 tools/check-games.py                  check every game, update state, write ubg45-health.js and HEALTH.md
  python3 tools/check-games.py --dry-run        check and print, write nothing

What it does
  1. Reads every game card in index.html (title + address).
  2. Opens each address like a browser would. A game FAILS when its page is gone (HTTP 404/410), the site does not exist
     (DNS error, refused connection, bad certificate), or the "page" is really an error page (GitHub's "There isn't a
     GitHub Pages site here", a title that says 404 / not found). Slow, blocked or temporarily broken answers (timeouts,
     403, 429, 5xx) only produce a warning, never a strike.
  3. A game that fails in 2 checks in a row is written to ubg45-health.js, and the site then hides it automatically.
     A hidden game that passes again comes back by itself on the next check.
  4. Safety: nothing is changed when none of the control sites answer (the runner is offline) or when more than
     25% of all games fail at once (that looks like an outage or a blocked runner, not 100 broken games).
     Games listed in tools/health-ignore.txt are reported but never hidden.
  5. Writes HEALTH.md (human report) and, when the database is reachable, lists the games players reported most.
"""
import argparse, concurrent.futures as cf, datetime, html, json, os, re, socket, ssl, sys, threading, time
import urllib.error, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HIDE_AFTER = 2            # consecutive failed checks before a game is hidden
MAX_FAIL_RATIO = 0.25     # more failures than this share of all games = suspect run, change nothing
TIMEOUT = 20
UA = 'Mozilla/5.0 (compatible; UBG45-health-check/1.0; +https://ubg45.github.io/)'
CONTROLS = ['https://github.com/', 'https://pages.github.com/', 'https://www.wikipedia.org/']
HEAD = ('/* Generated by tools/check-games.py (weekly workflow). Games listed in "hidden" failed two checks in a row and are\n'
        ' * hidden by the site until they pass again. Do not edit by hand; use tools/health-ignore.txt to protect a game. */\n')


def norm(s):
    return re.sub(r'\s+', ' ', html.unescape(s)).strip().lower()


def slug(t):
    return re.sub(r'^-+|-+$', '', re.sub(r'[^a-z0-9]+', '-', t.lower())) or 'x'


def read_games(index_path):
    src = open(index_path, encoding='utf-8').read()
    grid = src[src.index('id="gameGrid"'):]
    out, seen = [], set()
    for m in re.finditer(r'<div class="game-card"[^>]*?onclick="openGame\(\'([^\']+)\'[^"]*"[^>]*>(.*?)</div>', grid, re.S):
        url, inner = html.unescape(m.group(1)), m.group(2)
        h = re.search(r'<h3>(.*?)</h3>', inner, re.S)
        title = re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', h.group(1)))).strip() if h else ''
        if title and url not in seen:
            seen.add(url); out.append({'title': title, 'url': url})
    return out


SOFT_BODY = [r"There isn't a GitHub Pages site here", r'<title>\s*Site not found', r'<title>\s*(?:error\s*)?404\b', r'<title>\s*(?:page\s+)?not\s+found',
             r'<title>\s*404\s*[-:|]?\s*not found', r'<title>\s*file not found', r'<title>\s*the page you.{0,20}looking for']
SOFT_RE = re.compile('|'.join(SOFT_BODY), re.I)


class NoRedirectLoop(urllib.request.HTTPRedirectHandler):
    max_redirections = 6


def fetch(url, timeout=TIMEOUT):
    """Returns (status, body_bytes, error). status is None when no HTTP answer came back."""
    req = urllib.request.Request(url, headers={'User-Agent': UA, 'Accept': 'text/html,application/xhtml+xml,*/*;q=0.8', 'Accept-Language': 'en'})
    opener = urllib.request.build_opener(NoRedirectLoop())
    try:
        with opener.open(req, timeout=timeout) as r:
            return r.status, r.read(65536), None
    except urllib.error.HTTPError as e:
        try:
            body = e.read(65536)
        except Exception:
            body = b''
        return e.code, body, None
    except urllib.error.URLError as e:
        return None, b'', e.reason if isinstance(e.reason, BaseException) else RuntimeError(str(e.reason))
    except (socket.timeout, TimeoutError) as e:
        return None, b'', e
    except Exception as e:                         # connection reset, incomplete read, etc.
        return None, b'', e


def classify_error(err):
    """dead = the site does not exist / refuses us for good; warn = might be temporary."""
    if isinstance(err, socket.gaierror):
        return 'dead', 'site not found (DNS)'
    if isinstance(err, ssl.SSLCertVerificationError) or (isinstance(err, ssl.SSLError) and 'CERTIFICATE' in str(err).upper()):
        return 'dead', 'bad security certificate'
    if isinstance(err, ConnectionRefusedError):
        return 'dead', 'connection refused'
    if isinstance(err, (socket.timeout, TimeoutError)) or 'timed out' in str(err).lower():
        return 'warn', 'timed out'
    return 'warn', 'network error: %s' % (str(err)[:80] or err.__class__.__name__)


def check_remote(url):
    status, body, err = fetch(url)
    if status is None:
        kind, why = classify_error(err)
        if kind == 'warn':                          # one retry for transient trouble
            time.sleep(2)
            status, body, err = fetch(url)
            if status is None:
                kind, why = classify_error(err)
                return kind, why
        else:
            return kind, why
    if status in (404, 410):
        return 'dead', 'HTTP %d (page gone)' % status
    if 200 <= status < 300:
        text = body.decode('utf-8', 'replace')
        if SOFT_RE.search(text[:20000]):
            return 'dead', 'error page served with status %d' % status
        if len(body) == 0:
            return 'dead', 'empty page'
        return 'ok', ''
    return 'warn', 'HTTP %d (blocked or temporary)' % status


def check_local(url, root):
    path = url.split('#')[0].split('?')[0]
    full = os.path.normpath(os.path.join(root, path.lstrip('/')))
    if not full.startswith(os.path.normpath(root)):
        return 'dead', 'outside the site folder'
    if os.path.isdir(full):
        full = os.path.join(full, 'index.html')
    return ('ok', '') if os.path.isfile(full) else ('dead', 'file missing in repo')


def run_checks(games, root, workers=12, per_host=3):
    locks, mu = {}, threading.Lock()

    def host_lock(h):
        with mu:
            return locks.setdefault(h, threading.Semaphore(per_host))

    def one(g):
        u = g['url']
        if not re.match(r'^https?://', u):
            return g, check_local(u, root)
        host = re.sub(r'^https?://([^/]+).*$', r'\1', u).lower()
        with host_lock(host):
            return g, check_remote(u)

    with cf.ThreadPoolExecutor(max_workers=workers) as ex:
        return list(ex.map(one, games))


def controls_ok(urls):
    for u in urls:
        s, _, _ = fetch(u, timeout=15)
        if s is not None and s < 500:
            return True
    return False


def load_state(path):
    try:
        d = json.load(open(path, encoding='utf-8'))
        return d if isinstance(d, dict) and isinstance(d.get('games'), dict) else {'games': {}}
    except Exception:
        return {'games': {}}


def load_ignore(path):
    out = set()
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            line = line.split('#')[0].strip()
            if line:
                out.add(norm(line))
    return out


def reported(cfg_path, days=14):
    """Games players reported most (from the Supabase function ubg45_reports_summary). Never fatal."""
    try:
        cfg = open(cfg_path, encoding='utf-8').read()
        u = re.search(r"supabaseUrl:\s*'([^']+)'", cfg).group(1).rstrip('/')
        k = re.search(r"supabaseKey:\s*'([^']+)'", cfg).group(1)
        req = urllib.request.Request(u + '/rest/v1/rpc/ubg45_reports_summary', data=json.dumps({'p_days': days}).encode(),
                                     headers={'Content-Type': 'application/json', 'apikey': k, 'User-Agent': UA}, method='POST')
        with urllib.request.urlopen(req, timeout=20) as r:
            rows = json.loads(r.read())
        return {str(x['id']): int(x['n']) for x in rows if x.get('id') and int(x.get('n') or 0) > 0}
    except Exception:
        return None


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--index', default=os.path.join(ROOT, 'index.html'))
    ap.add_argument('--root', default=ROOT, help='folder that relative game addresses are resolved against')
    ap.add_argument('--state', default=os.path.join(ROOT, 'tools', 'health-state.json'))
    ap.add_argument('--ignore', default=os.path.join(ROOT, 'tools', 'health-ignore.txt'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'ubg45-health.js'))
    ap.add_argument('--report', default=os.path.join(ROOT, 'HEALTH.md'))
    ap.add_argument('--config', default=os.path.join(ROOT, 'ubg45-config.js'))
    ap.add_argument('--controls', nargs='*', default=CONTROLS)
    ap.add_argument('--no-reports', action='store_true')
    ap.add_argument('--hide-after', type=int, default=HIDE_AFTER)
    ap.add_argument('--max-fail-ratio', type=float, default=MAX_FAIL_RATIO)
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args(argv)

    today = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')
    games = read_games(a.index)
    if len(games) < 20:
        print('Only %d games found in index.html - refusing to continue (card format changed?).' % len(games)); return 2
    state, ignore = load_state(a.state), load_ignore(a.ignore)
    prev_hidden = {u for u, v in state['games'].items() if v.get('fails', 0) >= a.hide_after and v.get('hidden')}

    online = controls_ok(a.controls)
    results = run_checks(games, a.root) if online else []
    dead = [(g, w) for g, (k, w) in results if k == 'dead']
    warn = [(g, w) for g, (k, w) in results if k == 'warn']
    ratio = len(dead) / len(games)
    verdict = 'ok'
    if not online:
        verdict = 'offline'
    elif ratio > a.max_fail_ratio:
        verdict = 'suspect'
    print('games: %d  failing: %d (%.0f%%)  warnings: %d  controls reachable: %s  verdict: %s' % (len(games), len(dead), ratio * 100, len(warn), online, verdict))

    games_state = state['games']
    newly, back = [], []
    if verdict == 'ok':
        dead_urls = {g['url'] for g, _ in dead}
        for g, w in dead:
            e = games_state.setdefault(g['url'], {'title': g['title'], 'fails': 0, 'since': today})
            e.update(title=g['title'], reason=w, fails=e.get('fails', 0) + 1, last=today)
            protected = norm(g['title']) in ignore or norm(g['url']) in ignore
            e['hidden'] = e['fails'] >= a.hide_after and not protected
            e['protected'] = protected
            if e['hidden'] and g['url'] not in prev_hidden:
                newly.append(g)
        for g in games:
            if g['url'] not in dead_urls and g['url'] in games_state:
                if g['url'] in prev_hidden:
                    back.append(g)
                del games_state[g['url']]
        known = {g['url'] for g in games}
        for u in list(games_state):                  # a game removed from index.html no longer needs tracking
            if u not in known:
                del games_state[u]
        state['updated'] = today
    hidden = sorted(u for u, v in games_state.items() if v.get('hidden')) if verdict == 'ok' else sorted(prev_hidden)

    titles = {g['url']: g['title'] for g in games}
    rep = None if a.no_reports else reported(a.config)
    lines = ['# UBG45 game health', '',
             'Last check: **%s** (UTC). Games checked: **%d**. Failing now: **%d**. Warnings: **%d**. Hidden on the site: **%d**.' % (today, len(games), len(dead), len(warn), len(hidden)), '']
    if verdict == 'offline':
        lines += ['> **Nothing was changed.** None of the control sites answered, so the checking computer was probably offline.', '']
    elif verdict == 'suspect':
        lines += ['> **Nothing was changed.** %d of %d games (%.0f%%) failed at once, which is more than the %.0f%% safety limit. That usually means an outage or a blocked checker, not a real problem with every game. '
                  'Look at the list below; if these really are gone, remove them from index.html or tell the owner of the host.' % (len(dead), len(games), ratio * 100, a.max_fail_ratio * 100), '']
    if newly:
        lines += ['## Hidden this week', ''] + ['- **%s** (%s) - %s' % (g['title'], g['url'], games_state[g['url']].get('reason', '')) for g in newly] + ['']
    if back:
        lines += ['## Back again (passed the check, no longer hidden)', ''] + ['- %s' % g['title'] for g in back] + ['']
    cur = [(u, v) for u, v in games_state.items() if v.get('hidden')]
    if cur:
        lines += ['## Hidden on the site', '', '| Game | Why | Failing since | Address |', '|---|---|---|---|'] + \
                 ['| %s | %s | %s | %s |' % (v.get('title', ''), v.get('reason', ''), v.get('since', ''), u) for u, v in sorted(cur, key=lambda x: x[1].get('title', '').lower())] + ['']
    strike = [(u, v) for u, v in games_state.items() if not v.get('hidden') and v.get('fails')]
    if strike:
        lines += ['## Failed once (hidden if it fails again next week)', '', '| Game | Why | Address |', '|---|---|---|'] + \
                 ['| %s | %s | %s |%s' % (v.get('title', ''), v.get('reason', ''), u, ' protected by tools/health-ignore.txt' if v.get('protected') else '') for u, v in sorted(strike, key=lambda x: x[1].get('title', '').lower())] + ['']
    if verdict == 'suspect':
        lines += ['## Failing in this check (not recorded)', '', '| Game | Why | Address |', '|---|---|---|'] + \
                 ['| %s | %s | %s |' % (g['title'], w, g['url']) for g, w in sorted(dead, key=lambda x: x[0]['title'].lower())] + ['']
    if warn:
        lines += ['## Warnings (not counted)', '', 'Slow, blocked or temporarily broken answers. These games stay visible.', '', '| Game | Why | Address |', '|---|---|---|'] + \
                 ['| %s | %s | %s |' % (g['title'], w, g['url']) for g, w in sorted(warn, key=lambda x: x[0]['title'].lower())] + ['']
    if rep:
        by_slug = {slug(t): t for t in titles.values()}
        top = sorted(rep.items(), key=lambda x: -x[1])[:15]
        lines += ['## Reported by players (last 14 days)', '', 'Players pressed "Report a broken game". These are only a hint: the weekly check above decides what gets hidden.', '', '| Game | Reports |', '|---|---|'] + \
                 ['| %s | %d |' % (by_slug.get(k, k), n) for k, n in top] + ['']
    lines += ['---', 'To stop a game from ever being hidden, add its title or address to `tools/health-ignore.txt`. To run the check by hand: Actions tab, "Check games", Run workflow.', '']

    js = HEAD + '(window.UBG45 = window.UBG45 || {}).health = ' + json.dumps({'checked': today if verdict == 'ok' else state.get('updated'), 'hidden': hidden}, indent=1) + ';\n'
    if a.dry_run:
        print('\n'.join(lines)); print(js); return 0
    open(a.out, 'w', encoding='utf-8').write(js)
    open(a.report, 'w', encoding='utf-8').write('\n'.join(lines))
    if verdict == 'ok':
        json.dump(state, open(a.state, 'w', encoding='utf-8'), indent=1, sort_keys=True, ensure_ascii=False); open(a.state, 'a').write('\n')
    print('hidden now: %d (new %d, back %d)' % (len(hidden), len(newly), len(back)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
