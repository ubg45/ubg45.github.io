#!/usr/bin/env python3
"""Stamp the date each game first appeared in index.html into ubg45-added.js.

  python3 tools/stamp-added.py              stamp games that are not in the file yet with today's date (UTC)
  python3 tools/stamp-added.py --baseline   stamp every missing game as "old" (2000-01-01) - used once at setup

Games already in the file keep their original date, and removed games keep their entry, so a game never
becomes "New" twice. The site shows a game as New for NEW_DAYS days (ubg45-config.js) after its date.
"""
import datetime, hashlib, html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX, OUT = os.path.join(ROOT, 'index.html'), os.path.join(ROOT, 'ubg45-added.js')
HEAD = ('/* Generated by tools/stamp-added.py - first-seen date for each game (UTC). Do not edit by hand.\n'
        ' * Games dated 2000-01-01 were already on the site when automatic tagging started. */\n')

def norm(s): return re.sub(r'\s+', ' ', html.unescape(s)).strip().lower()

def titles():
    src = open(INDEX, encoding='utf-8').read()
    grid = src[src.index('id="gameGrid"'):]
    out = []
    for card in re.findall(r'<div class="game-card"[^>]*>(.*?)</div>', grid, re.S):
        m = re.search(r'<h3>(.*?)</h3>', card, re.S)
        if m and norm(re.sub(r'<[^>]+>', '', m.group(1))): out.append(norm(re.sub(r'<[^>]+>', '', m.group(1))))
    return out

def load():
    if not os.path.exists(OUT): return {}
    m = re.search(r'\)\.added\s*=\s*(\{.*\});', open(OUT, encoding='utf-8').read(), re.S)
    return json.loads(m.group(1)) if m else {}

ASSETS = ['ubg45.css', 'ubg45-settings.js', 'ubg45-config.js', 'ubg45-added.js', 'ubg45-news.js', 'ubg45-stats.js', 'ubg45-social.js', 'ubg45-info.js', 'ubg45-gametab.js', 'ubg45-health.js', 'ubg45.js']

def bust():
    """Add/refresh ?v=<hash> on the site's own css/js tags so browsers always fetch the newest files."""
    src = open(INDEX, encoding='utf-8').read(); out = src
    for name in ASSETS:
        path = os.path.join(ROOT, name)
        if not os.path.exists(path): continue
        h = hashlib.sha1(open(path, 'rb').read()).hexdigest()[:8]
        out = re.sub(r'((?:href|src)=")%s(?:\?v=[0-9a-f]+)?(")' % re.escape(name), r'\g<1>%s?v=%s\g<2>' % (name, h), out)
    if out != src: open(INDEX, 'w', encoding='utf-8').write(out)
    return out != src

def main():
    baseline = '--baseline' in sys.argv
    today = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')
    added, new = load(), []
    for t in titles():
        if t not in added:
            added[t] = '2000-01-01' if baseline else today
            new.append(t)
    body = ',\n'.join('  %s: %s' % (json.dumps(k, ensure_ascii=False), json.dumps(v)) for k, v in added.items())
    open(OUT, 'w', encoding='utf-8').write(HEAD + '(window.UBG45 = window.UBG45 || {}).added = {\n' + body + '\n};\n')
    print('cache-bust tags updated' if bust() else 'cache-bust tags already current')
    print('stamped %d new game(s)%s' % (len(new), ': ' + ', '.join(new) if new and len(new) < 20 else ''))

if __name__ == '__main__': main()
